
package Tugas5Prak;

public class No7 {
    public static void main(String[] args) {

        int i = 1;

        System.out.println("Menggunakan i++ :");

        while(i <= 5){
            System.out.println(i++);
        }

        i = 1;

        System.out.println("Menggunakan ++i :");

        while(i <= 5){
            System.out.println(++i);
        }

    }
}
